async function download(url) {
  for (let attempt = 1; ; attempt++) {
    try {
      const response = await fetch(url, { signal: AbortSignal.timeout(30_000) });
      if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
      return await response.text();
    } catch (error) {
      if (attempt === 3) throw error;
    }
  }
}

const quote = (value) => JSON.stringify(value);

/** Fields of an ISO 4217 entry (fixed patterns). */
const TAGS = {
  Ccy: /<Ccy>([^<]*)<\/Ccy>/,
  CcyNm: /<CcyNm[^>]*>([^<]*)<\/CcyNm>/,
  CcyNbr: /<CcyNbr>([^<]*)<\/CcyNbr>/,
  CcyMnrUnts: /<CcyMnrUnts>([^<]*)<\/CcyMnrUnts>/,
};

function file(header, model, records) {
  const lines = records.map(
    ({ id, values }) =>
      `  { id: ${quote(id)}, values: { ${Object.entries(values)
        .map(([key, value]) =>
          typeof value === 'object' && value?.ref
            ? `${key}: ref(${quote(value.ref)})`
            : `${key}: ${quote(value)}`,
        )
        .join(', ')} } },`,
  );
  const usesRef = records.some(({ values }) =>
    Object.values(values).some((v) => typeof v === 'object' && v?.ref),
  );
  return `// SPDX-License-Identifier: LGPL-3.0-only
//
${header.map((line) => `// ${line}`.trimEnd()).join('\n')}
//
// Generated by scripts/data/generate-base-data.mjs — do not edit by hand.
import { defineData${usesRef ? ', ref' : ''} } from '@socle/framework';

export default defineData(${quote(model)}, [
${lines.join('\n')}
]);
`;
}

async function currencies() {
  const xml = await download(ISO_4217);
  const published = /Pblshd="([^"]+)"/.exec(xml)?.[1] ?? 'unknown';
  const entries = new Map();
  for (const [, body] of xml.matchAll(/<CcyNtry>([\s\S]*?)<\/CcyNtry>/g)) {
    const tag = (pattern) => pattern.exec(body)?.[1]?.trim();
    const code = tag(TAGS.Ccy);
    const minor = tag(TAGS.CcyMnrUnts);
    // Entries without a currency, funds and units without minor units (gold, SDR…) are left out.
    if (!code || !/^\d$/.test(minor ?? '') || entries.has(code)) continue;
    entries.set(code, {
      id: code.toLowerCase(),
      values: {
        code,
        name: new Intl.DisplayNames(['fr'], { type: 'currency' }).of(code) ?? tag(TAGS.CcyNm),
        numericCode: tag(TAGS.CcyNbr),
        decimals: Number(minor),
        active: ACTIVE_CURRENCIES.has(code),
      },
    });
  }
  const records = [...entries.values()].sort((a, b) => (a.id < b.id ? -1 : 1));
  return file(
    [
      `Currencies: ISO 4217 list one, SIX Group, published ${published} (${ISO_4217}).`,
      '`decimals` is the ISO minor unit: amounts are stored as integers of that unit.',
      'French names from Unicode CLDR (ICU of Node.js).',
    ],
    'res.currency',
    records,
  );
}

function countries() {
  const names = new Intl.DisplayNames(['fr'], { type: 'region', fallback: 'none' });
  const records = [];
  for (let a = 65; a <= 90; a++) {
    for (let b = 65; b <= 90; b++) {
      const code = String.fromCharCode(a, b);
      if (NOT_COUNTRIES.has(code)) continue;
      const name = names.of(code);
      // Deprecated codes (e.g. BU → MM) canonicalise to another region: left out.
      const canonical = new Intl.Locale(Intl.getCanonicalLocales(`und-${code}`)[0] ?? '').region;
      if (!name || canonical !== code) continue;
      records.push({ id: code.toLowerCase(), values: { code, name } });
    }
  }
  return file(
    [
      `Countries: ISO 3166-1 alpha-2 codes with their French names from Unicode CLDR`,
      `(ICU ${process.versions.icu}, CLDR ${process.versions.cldr ?? '?'}, Node.js ${process.version}).`,
      'Names are shown in the user language by the client (Intl.DisplayNames).',
    ],
    'res.country',
    records,
  );
}

async function frenchDepartements() {
  const csv = await download(COG_DEPARTEMENTS);
  const rows = csv
    .trim()
    .split(/\r?\n/)
    .slice(1)
    .map((line) => line.split(',').map((cell) => cell.replace(/^"|"$/g, '')));
  const records = rows.map(([code, , , , , , label]) => ({
    id: `fr_${code.toLowerCase()}`,
    values: { countryId: { ref: 'base.fr' }, code, name: label },
  }));
  return file(
    [
      `France: départements of the Code officiel géographique ${COG_YEAR}, INSEE`,
      `(${COG_DEPARTEMENTS}), Licence Ouverte 2.0.`,
    ],
    'res.country.state',
    records,
  );
}

function wilayas() {
  const records = WILAYAS.map((name, index) => {
    const code = String(index + 1).padStart(2, '0');
    return { id: `dz_${code}`, values: { countryId: { ref: 'base.dz' }, code, name } };
  });
  return file(
    [
      'Algeria: the 58 wilayas and their codes — loi n° 84-09 du 4 février 1984 (wilayas 01-48)',
      'and loi n° 19-12 du 11 décembre 2019 (wilayas 49-58, JORADP n° 78 du 18 décembre 2019).',
      'To be checked against any later territorial reform before each release.',
    ],
    'res.country.state',
    records,
  );
}

const outputs = {
  '01-currencies.ts': await currencies(),
  '02-countries.ts': countries(),
  '03-states-fr.ts': await frenchDepartements(),
  '04-states-dz.ts': wilayas(),
};
await mkdir(OUT, { recursive: true });
for (const [name, content] of Object.entries(outputs)) {
  await writeFile(join(OUT, name), content);
  console.log(`wrote modules/base/data/${name}`);
}
